const assert = require('node:assert/strict');
const path = require('node:path');
const { buildSync } = require('esbuild');
const result = buildSync({ entryPoints: [path.join(__dirname, '../src/worker/launch.ts')], bundle: true, platform: 'node', format: 'cjs', write: false });
const mod = { exports: {} };
new Function('module', 'exports', result.outputFiles[0].text)(mod, mod.exports);
const { getWorkerLaunch } = mod.exports;
assert.equal(getWorkerLaunch({ sdkVersion: '58.0.0', extra: { snackChannel: 'legacy' } }), null);
assert.equal(getWorkerLaunch({ sdkVersion: '56.0.0' }), null);
const config = extra => ({sdkVersion: '58.0.0', extra: {snackCompiler: 'snack-worker-graph@1', ...extra}});
assert.deepEqual(getWorkerLaunch(config({snackChannel:'test', snackpubURL:'https://snackpub.expo.dev'})), {channel:'test',url:'https://snackpub.expo.dev',snackId:undefined,apiURL:undefined});
assert.equal(getWorkerLaunch(config({snackId:'@user/project',snackApiURL:'https://api.expo.dev'})).snackId, '@user/project');
assert.throws(() => getWorkerLaunch({...config({}),sdkVersion:'56.0.0'}), /SDK 58/);
assert.throws(() => getWorkerLaunch(config({})), /requires/);
assert.throws(() => getWorkerLaunch(config({snackId:'../private'})), /identifier/);
assert.throws(() => getWorkerLaunch(config({snackChannel:'test',snackpubURL:'https://user:password@example.com'})), /HTTPS/);
assert.throws(() => getWorkerLaunch(config({snackChannel:'test',snackpubURL:'http://example.com'})), /HTTPS/);
console.log('Runtime launch selection: legacy, worker live/saved, incompatible SDK and invalid origins passed');
const services = {url:'https://snackpub.expo.dev',apiURL:'https://api.expo.dev'};
assert.equal(getWorkerLaunch({sdkVersion:'58.0.0'}, 'exp://u.expo.dev/project?snack-channel=legacy', services), null);
assert.deepEqual(getWorkerLaunch({sdkVersion:'58.0.0'}, 'exp://u.expo.dev/project?compiler=worker&snack-channel=live&snack=%40user%2Fproject', services), {channel:'live',url:services.url,snackId:'@user/project',apiURL:services.apiURL});
console.log('Standard EAS launch URLs select worker execution only with explicit opt-in');
